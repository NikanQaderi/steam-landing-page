//search
search = document.getElementById("search");

search.onkeyup = function () {
  searchResult.className = "show";
  var searched = [];
  searched = gamesDatabase.filter(
    (el) =>
      el.gameName.toLowerCase().indexOf(this.value.toLowerCase()) != -1 &&
      this.value != "",
  );
  // getGameCardData(searched , "searchResult")
  fillSearch(searched);
};
function fillSearch(jsonData) {
  searchResult.innerHTML = "";
  if (jsonData.length > 0) {
    let searchTitle = document.createElement("div");
    searchTitle.className = "searchResultTitle";
    searchTitle.innerHTML = "Search results";
    searchResult.appendChild(searchTitle);
  }
  for (i = 0; i < jsonData.length; i++) {
    let searchItems = document.createElement("div");
    searchItems.id = "searchItems";
    searchItems.dataset.gameId = jsonData[i].id;

    searchItems.addEventListener("click", function (event) {
      const searchResult = document.getElementById("searchResult");
      const gameId = this.dataset.gameId;
      fillGamePageDetails(gameId);
      showGamePage();
      searchResult.className = "";
      searchResult.innerHTML = "";
    });

    let image = document.createElement("img");
    image.src = "game-image/undercontent/" + jsonData[i].gamepic;
    image.className = "searchImage";

    let span = document.createElement("div");
    span.innerHTML = jsonData[i].gameName;
    span.className = "SearchgameName";

    searchItems.appendChild(image);
    searchItems.appendChild(span);
    searchResult.appendChild(searchItems);
  }
}
//load gamepage detail
function fillGamePageDetails(gameId) {
  let bookPageDetail = gamesDatabase.find((el) => el.id == gameId);

  const GamePageContainer = document.getElementById("gameDetailContainer");
  GamePageContainer.innerHTML = "";

  let gameGallerySlider = document.createElement("div");
  gameGallerySlider.id = "gameGallerySliderContainer";

  let gamevideo = document.createElement("video");
  gamevideo.autoplay = true;
  gamevideo.loop = true;
  gamevideo.muted = true;

  let gamesource = document.createElement("source");
  gamesource.src =
    "videos/gameCards/microtrailer" + bookPageDetail.gamevideoData;
  gamesource.type = "video/webm";

  gamevideo.appendChild(gamesource);
  gameGallerySlider.appendChild(gamevideo);

  let gameItemDescription = document.createElement("div");
  gameItemDescription.id = "gameDescription";

  let gamePageImage = document.createElement("img");
  gamePageImage.src = "game-image/undercontent/" + bookPageDetail.gamepic;

  let DescriptionSnippet = document.createElement("span");
  DescriptionSnippet.className = "gameDescriptionSnippet";
  DescriptionSnippet.innerHTML = bookPageDetail.gameDetails;

  let GameName = document.createElement("span");
  GameName.id = "descriptionGameName";
  GameName.innerHTML = bookPageDetail.gameName;

  let CompaniName = document.createElement("span");
  CompaniName.id = "descriptionCompaniName";
  CompaniName.innerHTML = "Compani name : ";

  let CompaniNameSpan = document.createElement("span");
  CompaniNameSpan.innerHTML = bookPageDetail.gameCompanyName;
  CompaniName.appendChild(CompaniNameSpan);

  let peopleVote = document.createElement("span");
  peopleVote.id = "peopleVote";
  peopleVote.innerHTML = "Overwhelmingly Positive (113,165)";

  let underbutton = document.createElement("button");
  underbutton.innerHTML = "Add to Chart";
  underbutton.id = "gameItemButton";
  underbutton.setAttribute("data-id", gameId);
  underbutton.addEventListener("click", function () {
    let CurrentID = this.getAttribute("data-id");

    let currentGame = gamesDatabase.find((el) => el.id == CurrentID);

    let elementId = currentGame.id;
    let elementPic = currentGame.gamepic;
    let elementTitle = currentGame.gameName;

    let ProfileDataBase = JSON.parse(localStorage.getItem("informationLeft"));
    if (!ProfileDataBase) ProfileDataBase = [];

    let ProfileIndex = ProfileDataBase.findIndex(
      (x) => x.elementId == CurrentID,
    );

    if (ProfileIndex === -1) {
      ProfileDataBase.push({ elementId, elementPic, elementTitle });
      localStorage.setItem("informationLeft", JSON.stringify(ProfileDataBase));
      AddtoProfile();

      alert("game is added");
    } else {
      alert("already added");
    }
  });

  gameItemDescription.appendChild(gamePageImage);
  gameItemDescription.appendChild(DescriptionSnippet);
  gameItemDescription.appendChild(GameName);
  gameItemDescription.appendChild(CompaniName);
  gameItemDescription.appendChild(peopleVote);
  gameItemDescription.appendChild(underbutton);

  GamePageContainer.appendChild(gameGallerySlider);
  GamePageContainer.appendChild(gameItemDescription);
}

//add game to profile or delet game from profile

const informationLeft = document.getElementById("informationLeft");
function deleteGameFromProfile(id) {
  let ProfileDataBase =
    JSON.parse(localStorage.getItem("informationLeft")) || [];

  ProfileDataBase = ProfileDataBase.filter((item) => item.elementId != id);

  localStorage.setItem("informationLeft", JSON.stringify(ProfileDataBase));

  AddtoProfile();
}
function AddtoProfile() {
  console.log("AddtoProfile RUN!");
  let ProfileDataBase = JSON.parse(localStorage.getItem("informationLeft"));
  if (!ProfileDataBase || ProfileDataBase.length === 0) {
    return;
  }
  informationLeft.innerHTML = "";
  ProfileDataBase.forEach((element) => {
    let informationGameList = document.createElement("div");
    informationGameList.id = "informationGameList";

    let ProfileGameIMG = document.createElement("img");
    ProfileGameIMG.src = "game-image/undercontent/" + element.elementPic;

    let ProfileGameName = document.createElement("span");
    ProfileGameName.id = "MygameName";
    ProfileGameName.innerHTML = element.elementTitle;

    let ProfileGameTimePlay = document.createElement("span");
    ProfileGameTimePlay.innerHTML = "99h";

    let deleButton = document.createElement("button");
    deleButton.id = "ProfileGameDelet";
    deleButton.innerHTML = "❌";

    deleButton.addEventListener("click", function () {
      deleteGameFromProfile(element.elementId);
    });

    ProfileGameName.appendChild(ProfileGameTimePlay);
    informationGameList.appendChild(ProfileGameIMG);
    informationGameList.appendChild(ProfileGameName);
    informationGameList.appendChild(deleButton);
    informationLeft.appendChild(informationGameList);
  });
  localStorage.setItem("informationLeft", JSON.stringify(ProfileDataBase));
}

